package com.example.messenger.model;

/**
 * Site-wide role, ordered from least to most privileged.
 * USER       — обычный пользователь, без доступа к панели администратора.
 * MODERATOR  — модерация: баны/разбаны, верификация, очередь жалоб. Не видит настройки,
 *              журнал действий, не может удалять пользователей, рассылать объявления или
 *              менять роли.
 * ADMIN      — всё, что может MODERATOR, плюс удаление пользователей, рассылка,
 *              принудительное завершение сессий, просмотр журнала действий.
 * SUPER_ADMIN — всё, что может ADMIN, плюс изменение настроек платформы и выдача/снятие
 *              ролей другим пользователям (включая назначение других администраторов).
 */
public enum Role {
    USER,
    MODERATOR,
    ADMIN,
    SUPER_ADMIN
}
